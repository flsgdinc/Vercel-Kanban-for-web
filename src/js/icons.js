export function hydrateDataIcons(root) {
  if (!root) return;
  root.querySelectorAll('[data-ico]').forEach((el) => {
    const key = el.dataset.ico;
    const size = parseInt(el.dataset.icoSize || '16', 10);
    const cls = el.dataset.icoClass || 'ico';
    const p = shapes[key];
    if (p) el.innerHTML = icon(p, size, cls);
  });
}
